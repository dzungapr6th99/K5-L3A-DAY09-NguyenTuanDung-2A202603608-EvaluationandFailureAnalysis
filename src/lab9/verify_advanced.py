"""Reproduce core/advanced reports and evidence: python -m lab9.verify_advanced.

Reports are generated by the evaluation harness, never patched by this script.
Run from src. No provider credentials or network are needed.
"""
from __future__ import annotations

import contextlib
import hashlib
import io
import json
import subprocess
from pathlib import Path

from lab8.console import utf8_stdio
from lab9 import evalset, gate, mutation, traps, variants
from lab9.eval import load_spec, run_eval
from lab9.graders import GRADERS
from lab9.judge import calibrate


def write_json(path, value):
    Path(path).write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8", newline="\n")


def main():
    utf8_stdio()
    variants.register()
    evalset.build_v2()
    assert not evalset.check() and not evalset.check(evalset.ITEMS_V2, evalset.LABELS_V2)
    reports = {}
    evidence = {"gate": {}, "aa": {}, "traps": {}, "judge": {}}
    for version, shapes in ((1, ["swarm", "fixed", "seeded_regression"]),
                            (2, ["swarm", *mutation.EXPECTED])):
        spec = load_spec(Path(f"config/metric_spec{'_v2' if version == 2 else ''}.yaml"))
        reports[version] = {}
        for shape in shapes:
            rep = run_eval(shape, spec)
            assert not rep["evaluator_failures"], rep["evaluator_failures"]
            name = f"baseline_v{version}" if shape == "swarm" else f"eval_{shape}" + ("_v2" if version == 2 else "")
            write_json(f"reports/{name}.json", rep)
            reports[version][shape] = rep
            print(f"v{version} {shape}: pass_rate={rep['metrics']['pass_rate']}", flush=True)
        base = reports[version]["swarm"]
        for shape, rep in reports[version].items():
            blocked, lines = gate.check(rep, base, spec)
            evidence["gate"][f"v{version}/{shape}"] = {"blocked": blocked, "lines": lines}
            assert bool(blocked) == (mutation.EXPECTED.get(shape, "merge") == "block"), (shape, blocked)

    spec = load_spec(Path("config/metric_spec_v2.yaml"))
    assert evidence["gate"]["v2/slice_regression"]["blocked"] == ["slice:money_movement/pass_rate"]
    base = reports[2]["swarm"]
    alt = run_eval("swarm", spec, [66, 77, 88, 99, 110])
    write_json("reports/aa_alternate_v2.json", alt)
    evidence["aa"] = {k: {"default": v, "alternate": alt["metrics"][k], "delta": alt["metrics"][k] - v}
                      for k, v in base["metrics"].items()}
    assert all(v["delta"] == 0 for v in evidence["aa"].values())
    print("A/A: all deltas 0", flush=True)
    v1spec = load_spec()
    bad = {m["id"]: "max" in m.get("threshold", {}) for m in v1spec["metrics"]
           if m["id"] in GRADERS and m["id"] != "pass_rate"}
    flagged = lambda row: any(row.get(k) is v for k, v in bad.items())
    broken = [r for r in reports[1]["seeded_regression"]["rows"] if r["pass_rate"] is False]
    clean = reports[1]["fixed"]["rows"]
    evidence["detection_v1"] = {"detection": sum(map(flagged, broken)) / len(broken),
                                "false_alarms": sum(map(flagged, clean)) / len(clean)}
    assert evidence["detection_v1"]["detection"] >= .8
    assert evidence["detection_v1"]["false_alarms"] <= .1
    for name, (rep, loose) in traps.build(reports[2]["slice_regression"], spec).items():
        blocked, lines = gate.check(rep, base, loose or spec, spec if loose else None)
        assert blocked == ["integrity"], (name, blocked)
        evidence["traps"][name] = {"blocked": blocked, "lines": lines}
    for name in ("tone", "helpful"):
        evidence["judge"][name] = calibrate(Path(f"data/eval/judge_{name}_public.csv"))

    for name, function, args in (
        ("mutation_v2", mutation.main, ["--spec", "config/metric_spec_v2.yaml", "--baseline", "reports/baseline_v2.json"]),
        ("traps_v2", traps.main, ["--pr", "reports/eval_slice_regression_v2.json", "--baseline", "reports/baseline_v2.json", "--spec", "config/metric_spec_v2.yaml"]),
    ):
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            status = function(args)
        Path(f"reports/{name}.txt").write_text(output.getvalue(), encoding="utf-8", newline="\n")
        print(output.getvalue(), flush=True)
        assert status == 0
    write_json("reports/advanced_evidence.json", evidence)
    # Identify the actual source snapshot without inventing an uncommitted SHA.
    paths = sorted([*Path("lab9").glob("*.py"), *Path("config").glob("*.yaml"),
                    *Path("data/eval").glob("eval_set_v*.jsonl"), *Path("data/eval").glob("labels_v*.json")])
    files = {str(p).replace("\\", "/"): hashlib.sha256(p.read_bytes().replace(b"\r\n", b"\n")).hexdigest()
             for p in paths}
    commit = subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip()
    manifest = {"base_commit": commit, "advanced_changes_committed": False,
                "hash_normalization": "CRLF normalized to LF", "files": files,
                "snapshot_sha256": hashlib.sha256(json.dumps(files, sort_keys=True).encode()).hexdigest()}
    write_json("reports/source_manifest_v2.json", manifest)
    print("All core/advanced checks passed; source snapshot", manifest["snapshot_sha256"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
